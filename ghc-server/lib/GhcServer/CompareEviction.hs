-- | Description: Standalone benchmark (@compare-eviction@) comparing lazy bytecode cache memory behavior with and
-- without eviction ('Types.FeatureFlags.lazyByteCodeCacheLimit'), measuring actual GHC heap residency ("live bytes",
-- via 'GHC.Stats.getRTSStats') rather than the coarse BCO-count proxy used by
-- 'ConcurrentInterpretedTest.test_bcoEvictionConcurrentInterpreted'.
--
-- The scenario mirrors that test's shape (a shared module imported by every leaf, plus one large per-leaf helper
-- module, spliced against via Template Haskell and executed through the production eval path), but runs many more
-- iterations sequentially in a single worker session, each iteration adding a *new* leaf with its own large helper
-- module. Without eviction, the tracked bytecode (and the live heap bytes behind it) grows without bound as more
-- leaves accumulate; with eviction enabled, older leaves' bytecode is unloaded once the tracked size exceeds a
-- configured limit, and live bytes should stay roughly within a bound instead of growing linearly with iteration
-- count.
--
-- Each helper module is generated by 'Test.Source.fatModuleSource': it contains @--functions@ top-level
-- @'Int' -> 'Int'@ functions each with @--case-arms@ integer case alternatives.  Empirically, the count of
-- functions (top-level bindings, hence distinct BCOs) is the dominant lever on the freed heap per evicted module,
-- not the arms per function -- see the haddock on 'Test.Source.fatModuleSource' for the measurements behind this.
-- The defaults below were chosen to give a heap difference in the tens of megabytes within a benchmark run of
-- well under a minute.
module GhcServer.CompareEviction (
  main_compareEviction,
) where

